import {readFile,stat} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import vm from 'node:vm';
const storyRoot=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const root=path.resolve(storyRoot,'..');
const html=await readFile(path.join(storyRoot,'index.html'),'utf8');
const css=await readFile(path.join(storyRoot,'story.css'),'utf8');
const results=[];
function check(name,condition){results.push({name,pass:!!condition});if(!condition)throw Error(name);}
const blocks=[...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g)];
const ld=blocks.filter(x=>x[1].includes('application/ld+json')).map(x=>JSON.parse(x[2]));
check('Article JSON-LD parses',ld.length===1&&ld[0]['@type']==='NewsArticle');
for(const b of blocks.filter(x=>!x[1].includes('application/ld+json')&&!x[1].includes('src=')))new vm.Script(b[2]);
new vm.Script(await readFile(path.join(storyRoot,'story.js'),'utf8'));
check('JavaScript parses',true);
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(x=>x[1]);
check('Unique IDs',new Set(ids).size===ids.length);
for(const ref of html.matchAll(/href="#([^"]+)"/g))check(`Anchor #${ref[1]}`,ids.includes(ref[1]));
const refs=[...html.matchAll(/(?:href|src)="([^"#]+)"/g)].map(x=>x[1]).filter(x=>!/^https?:|^data:/.test(x));
for(const match of html.matchAll(/srcset="([^"]+)"/g))refs.push(...match[1].split(',').map(x=>x.trim().split(/\s+/)[0]));
for(const ref of new Set(refs)){let target=path.resolve(storyRoot,ref.split('?')[0]);if(ref.endsWith('/'))target=path.join(target,'index.html');check(`Local asset ${ref}`,(await stat(target)).isFile());}
check('Shared header reused',html.includes('../assets/visual-header.js'));
check('Shared carousel reused',html.includes('../assets/editshop-carousel.js'));
check('Shared brand banner reused',html.includes('../assets/editshop-brand-banner.css'));
const evidence=JSON.parse(await readFile(path.join(storyRoot,'editorial/photo-evidence.json'),'utf8'));
check('15 original provenance records retained',evidence.length===15);
check('Four selected originals have embedded captions',evidence.filter(x=>x.selected).length===4&&evidence.filter(x=>x.selected).every(x=>x.description));
check('Published article permits indexing',html.includes('content="index,follow,max-image-preview:large,max-snippet:-1,max-video-preview:-1"'));
check('Owner-approved publication date',ld[0].datePublished==='2026-11-04T05:00:00+09:00'&&html.includes('content="2026-11-04T05:00:00+09:00"'));
check('Source images not stretched or cropped',!css.includes('object-fit:cover'));
check('Reduced motion supported',css.includes('prefers-reduced-motion:reduce'));
const linear=n=>{const c=n/255;return c<=.04045?c/12.92:((c+.055)/1.055)**2.4;};
const luminance=hex=>hex.match(/\w\w/g).map(x=>linear(parseInt(x,16))).reduce((v,n,i)=>v+n*[.2126,.7152,.0722][i],0);
const contrast=(a,b)=>{const ls=[luminance(a),luminance(b)].sort((x,y)=>y-x);return (ls[0]+.05)/(ls[1]+.05);};
for(const [label,foreground,background] of [['body','20241f','f5f2eb'],['caption','65685f','f5f2eb'],['green','276b5e','f5f2eb'],['structure','20241f','e9ede3']])check(`Contrast ${label} ${contrast(foreground,background).toFixed(2)}:1`,contrast(foreground,background)>=4.5);
const carousel=await readFile(path.join(root,'assets/editshop-carousel.js'),'utf8');
for(const match of carousel.matchAll(/image:"([^"]+)"/g))check(`Carousel image ${match[1]}`,(await stat(path.join(root,'.'+match[1]))).isFile());
const response=await fetch(new URL('braille-100/', process.env.BRAILLE_PREVIEW_ORIGIN || 'http://127.0.0.1:8419/'));
check('Preview HTTP 200',response.status===200);
console.log(JSON.stringify({passed:results.length,results,releasePending:['Final title and canonical URL','Absolute OG/Twitter image URL','Publication date and indexing change','Editorial/point-user sign-off','Real iPhone Safari and Android Chrome checks']},null,2));
